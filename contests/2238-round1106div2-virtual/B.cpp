void solve() {
  int n;
  cin >> n;


  vector<vector<int>> factors(n+1);
  for (int f = 1; f <= n; f++) {
    for (int x = f; x <= n; x += f) {
      factors[x].pb(f);
    }
  }

  long total = 0;
  for (int a = 1; a <= n; a++) {
    for (int b : factors[a]) {
      // c that is a multiple of b
      long num_valid_c = LONG(n / b);
      total += num_valid_c;
    }
  }

  cout << total << "\n";

}










