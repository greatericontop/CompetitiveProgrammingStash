void solve() {
  int n, m;
  cin >> n >> m;

  cout << (n * m) << "\n";
  for (int i = 0; i < n; i++) {
    for (int j = 0; j < m; j++) {
      cout << (256 * i + j) << " \n"[j == m - 1];
    }
  }

}










int main() {
  ios::sync_with_stdio(false);
  cin.tie(nullptr);
  int t;
  cin >> t;
  while (t--)  solve();
  return 0;
}
