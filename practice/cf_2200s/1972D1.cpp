void solve() {
  int n, m;
  cin >> n >> m;

  long ct = 0;

  // b = g
  for (int g = 1; g <= m; g++) {
    // x = c*g - 1
    // find max c
    int max_x = n / g;
    int max_c = (max_x + 1) / g;
    if (g == 1)  max_c--;  //c=1 is invalid here
    if (max_c >= 1)  ct += max_c;
  }

  cout << ct << "\n";

}










