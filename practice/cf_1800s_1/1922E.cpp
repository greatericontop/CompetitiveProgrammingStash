void solve() {
  long x;
  cin >> x;
  if (x == 2) {
    cout << "1\n0\n";
    return;
  }
  int exp = 0;
  while ((1LL<<(exp+1)) <= x)  exp++;
  assert((1LL<<(exp+1)) > x);
  assert((1LL<<exp) <= x);

  // output 0 1 2 ... exp-1 (exp numbers for 2^exp subseqs)
  vector<int> ans;
  for (int i = 0; i < exp; i++)  ans.pb(i);

  x -= (1LL<<exp);
  // now highest x has all bits 0 through exp-1 set
  for (int b = exp-1; b >= 0; b--) {
    if (x & (1LL<<b)) {
      ans.pb(b);
    }
  }

  cout << ans.size() << "\n";
  for (int y : ans)  cout << y << " ";
  cout << "\n";

}










int main() {
  ios::sync_with_stdio(false);
  cin.tie(nullptr);
  int t = 1;
  cin >> t;
  while (t--)  solve();
  return 0;
}

