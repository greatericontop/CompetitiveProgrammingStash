long score(int n, long b, long x, const vector<int>& c, int squadcount) {
  long penalty = (squadcount - 1) * x;
  long strengths = 0;
  for (int ct : c) {
    // split ct into squadcount squads
    long total_interactions = LONG(ct) * LONG(ct-1) / 2;
    long size_small = ct / squadcount;  long size_large = size_small + 1;
    long num_large = ct % squadcount;  long num_small = squadcount - num_large;
    long interactions_lost_small = num_small * size_small * (size_small-1) / 2;
    long interactions_lost_large = num_large * size_large * (size_large-1) / 2;
    strengths += total_interactions - interactions_lost_small - interactions_lost_large;
  }
  return b * strengths - penalty;
}



