int calc(string s) {
  assert(s.size() == 11);

  int first_ct = 0;
  int second_ct = 0;
  for (int i = 1; i <= 10; i++) {
    if (i % 2 == 1) {
      // first team
      if (s[i] == '1')  first_ct++;
    } else {
      // second team
      if (s[i] == '1')  second_ct++;
    }

    int first_winning_by = first_ct - second_ct;
    if (first_winning_by > (11-i)/2) {
      return i;
    }
    int second_winning_by = second_ct - first_ct;
    if (second_winning_by > (10-i)/2) {
      return i;
    }
  }
  return 10;
}



void solve() {
  string s;  cin >> s;  s = '.' + s;

  string s1 = s;
  for (int i = 0; i < s.size(); i++) {
    if (s1[i] == '?')  s1[i] = i % 2 == 0 ? '1' : '0';
  }
  string s2 = s;
  for (int i = 0; i < s.size(); i++) {
    if (s2[i] == '?')  s2[i] = i % 2 == 0 ? '0' : '1';
  }
  fprintf(stderr, "%s, %s\n", s1.c_str(), s2.c_str());

  int a1 = calc(s1);
  int a2 = calc(s2);
  cout << min(a1, a2) << endl;
}










